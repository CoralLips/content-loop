#!/usr/bin/env node
// video-loop/bin/align-shot.mjs
// 把已知 narration（shots/<id>.json）和 whisper 的段时间对齐，产出 phrase→frame 常量。
//
// 原理：whisper.cpp 1.5.5 在 CJK token 边界会输出 U+FFFD（3 byte UTF-8 被劈开）。
// 我们不信任 whisper 的 text，只信 whisper 的 timing；用稿件 narration 做金标准文本，
// 顺序走一遍段时间，把每个 narration 字映射到段起始时间，再找短语位置。
//
// 用法:
//   node bin/align-shot.mjs --shot shot07 --fps 30 \
//     --out src/compositions/SemanticRateDistortion/timing/shot07.ts

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';

const args = { shot: null, fps: 30, out: null };
for (let i = 2; i < process.argv.length; i++) {
  const k = process.argv[i];
  if (k === '--shot') args.shot = process.argv[++i];
  else if (k === '--fps') args.fps = parseInt(process.argv[++i], 10);
  else if (k === '--out') args.out = process.argv[++i];
}

if (!args.shot || !args.out) { console.error('need --shot <id> --out <ts>'); process.exit(2); }

const shotCfg = JSON.parse(await readFile(`shots/${args.shot}.json`, 'utf8'));
const timing = JSON.parse(await readFile(`public/${args.shot}.timing.json`, 'utf8'));

const narration = shotCfg.narration || '';
const phrases = shotCfg.phrases || [];
if (!narration) { console.error('shot config missing narration'); process.exit(2); }

// Clean narration: remove whitespace/newlines that whisper wouldn't segment
// (but keep punctuation as whisper includes them)
function cleanChar(c) {
  return c.replace(/\s/g, '');
}

const narrChars = [...narration].filter(c => cleanChar(c).length > 0);

// Walk segments & narration in parallel, assign each narration char a start time.
const segments = timing.segments || [];
const narrTimes = new Array(narrChars.length).fill(null);

let narrPos = 0;
let segIdx = 0;
const FFFD = '\uFFFD';

while (narrPos < narrChars.length && segIdx < segments.length) {
  const seg = segments[segIdx];
  const segText = (seg.text || '').trim();
  const segStart = seg.start;
  const segEnd = seg.end;

  if (!segText) { segIdx++; continue; }

  // If segment is pure FFFD (corrupted), assume it represents 1 narration char
  if (/^[\uFFFD]+$/.test(segText)) {
    narrTimes[narrPos] = segStart;
    narrPos++;
    segIdx++;
    continue;
  }

  // Try to match segText in narration at current position
  // whisper 可能把标点合并或拆分，用 chars 长度来匹配
  const segChars = [...segText].filter(c => cleanChar(c).length > 0);
  const segLen = segChars.length;
  if (segLen === 0) { segIdx++; continue; }

  // Best-effort match: take next segLen chars from narration, assign times proportionally
  for (let k = 0; k < segLen && narrPos + k < narrChars.length; k++) {
    const frac = segLen > 1 ? k / segLen : 0;
    narrTimes[narrPos + k] = segStart + frac * (segEnd - segStart);
  }
  narrPos += segLen;
  segIdx++;
}

// Fill any remaining with last known time + small increment
for (let i = 0; i < narrTimes.length; i++) {
  if (narrTimes[i] == null && i > 0) narrTimes[i] = narrTimes[i - 1];
}

// Build narrative-string representation for phrase lookup
const narrStr = narrChars.join('');

function findPhraseFrame(phrase) {
  // Strip whitespace from phrase
  const cleanPhrase = [...phrase].filter(c => cleanChar(c).length > 0).join('');
  const idx = narrStr.indexOf(cleanPhrase);
  if (idx === -1) return null;
  const sec = narrTimes[idx];
  if (sec == null) return null;
  return Math.round(sec * args.fps);
}

const mapping = {};
const missing = [];
for (const p of phrases) {
  const f = findPhraseFrame(p);
  if (f == null) missing.push(p);
  else mapping[p] = f;
}

console.log(`[align] shot=${args.shot} fps=${args.fps}`);
console.log(`[align] narration chars: ${narrChars.length}, whisper segments: ${segments.length}`);
console.log(`[align] char-time coverage: ${narrTimes.filter(t => t != null).length}/${narrChars.length}`);
if (missing.length) {
  console.warn(`[align] 未定位 ${missing.length} 个短语: ${missing.map(m => `"${m}"`).join(', ')}`);
}
console.log(`[align] 对齐结果:`);
for (const [p, f] of Object.entries(mapping)) {
  console.log(`  "${p}" → frame ${f} (${(f / args.fps).toFixed(2)}s)`);
}

await mkdir(dirname(args.out), { recursive: true });
const ts = `// Auto-generated by bin/align-shot.mjs — do not edit by hand.
// Shot: ${args.shot}
// Generated: ${new Date().toISOString()}

export const phraseFrames = ${JSON.stringify(mapping, null, 2)} as const;

export type Phrase = keyof typeof phraseFrames;

export function frameOf(phrase: Phrase): number {
  return phraseFrames[phrase];
}
`;
await writeFile(args.out, ts, 'utf8');
console.log(`[align] wrote ${args.out}`);
